DECLARE CURPUBLICACIONES CURSOR
	FOR 
select NAME
	from sysmergepublications
	WHERE NOT NAME in('MAESTROS','INVESPECIAL')

OPEN CURPUBLICACIONES
DECLARE @pubname  VARCHAR(200)
FETCH NEXT FROM CURPUBLICACIONES INTO @pubname

WHILE @@FETCH_STATUS=0
BEGIN
	EXEC sp_changemergepublication @publication=@pubname, 
	@property= 'generation_leveling_threshold', 
	@value= '100000'
	RAISERROR (@PUBNAME,10,1)
	FETCH NEXT FROM CURPUBLICACIONES INTO @pubname
END

CLOSE CURPUBLICACIONES

DEALLOCATE CURPUBLICACIONES

