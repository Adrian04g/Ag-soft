CREATE PROCEDURE dbo.db_SP_LOG_TRAN_DATA_ProcessChanges
AS
BEGIN
	SET NOCOUNT ON;
	DECLARE curTablas CURSOR
		FOR SELECT cd_TBL_NAME FROM dbo.LOG_TBL_VERS
	DECLARE @cd_TBL_NAME VARCHAR(30)
	OPEN curTablas 
	FETCH NEXT FROM curTablas InTO @cd_TBL_NAME
	DECLARE @ds_Mensaje VARCHAR(200)
	WHILE @@FETCH_STATUS=0
	BEGIN
		SET @ds_Mensaje = 'Procesando tabla : ' + @cd_TBL_NAME
		RAISERROR(@ds_Mensaje,10,1) WITH NOWAIT
		EXEC db_SP_LOG_TRAN_DATA_GetChanges @cd_TBL_NAME
		FETCH NEXT FROM curTablas InTO @cd_TBL_NAME
	END
	CLOSE curTablas
	DEALLOCATE curTablas
END
GO
