CREATE PROCEDURE dbo.db_SP_LOG_TRAN_DATA_Initialize
AS
BEGIN
	IF (OBJECT_ID('LOG_TRAN_DATA','U') IS NULL)
	BEGIN
		CREATE TABLE LOG_TRAN_DATA(
			am_LOG_TRAN NUMERIC(20) IDENTITY(1,1),
			cd_TIP_TRAN VARCHAR(200) NOT NULL DEFAULT 'I',
			cd_BD_ORIG  VARCHAR(300) NOT NULL DEFAULT '',
			cd_LOG_STAT VARCHAR(200) NOT NULL DEFAULT 'P',
			cd_TBL_NAME VARCHAR(300) NOT NULL DEFAULT '',
			xm_DAT_TRAN XML,
			xm_KEY_TRAN XML,
			dt_LOG_FECHA SMALLDATETIME DEFAULT GETDATE() NOT NULL)
		ALTER TABLE dbo.LOG_TRAN_DATA ADD CONSTRAINT PK_LOG_TRAN_DATA PRIMARY KEY(am_LOG_TRAN)
		ALTER TABLE dbo.LOG_TRAN_DATA ADD CONSTRAINT CK_LOG_TRAN_DATA_TIP_TRAN CHECK(cd_TIP_TRAN IN ('I','U','D'))
		ALTER TABLE dbo.LOG_TRAN_DATA ADD CONSTRAINT CK_LOG_TRAN_DATA_LOG_STAT CHECK(cd_LOG_STAT IN ('P','E','A'))
	END 
	IF (OBJECT_ID('LOG_TBL_VERS','U') IS NULL)
	BEGIN
		CREATE TABLE LOG_TBL_VERS(
			cd_SRV_NOMB VARCHAR(200) NOT NULL DEFAULT @@SERVERNAME,
			cd_TBL_NAME VARCHAR(200) NOT NULL DEFAULT '',
			am_NUM_VERS NUMERIC(10) NOT NULL DEFAULT 0,
			dt_LOG_FECHA SMALLDATETIME DEFAULT GETDATE() NOT NULL)
		ALTER TABLE dbo.LOG_TBL_VERS ADD CONSTRAINT PK_LOG_TBL_VERS PRIMARY KEY(cd_SRV_NOMB,cd_TBL_NAME)
	END
	IF EXISTS(SELECT * FROM sys.change_tracking_databases WHERE database_id=DB_ID())
	BEGIN
		SELECT 'WARNING : El seguimiento de cambios ya se encuentra habilitado para esta base de datos'
		RETURN
	END
	DECLARE @ds_CadenaSQL NVARCHAR(4000)
	SET @ds_CadenaSQL = 'ALTER DATABASE ' + DB_NAME() + ' SET CHANGE_TRACKING = ON (CHANGE_RETENTION=100 DAYS,AUTO_CLEANUP=ON)'
	EXEC (@ds_CadenaSQL)
END
GO
