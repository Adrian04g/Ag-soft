CREATE PROCEDURE dbo.db_SP_LOG_TRAN_DATA_GetPendingData
	@cd_TBL_NAME VARCHAR(20)
AS
BEGIN
	SET NOCOUNT ON;
	DECLARE @ds_Datos VARCHAR(MAX)
	SET @ds_Datos ='
	DECLARE @hdoc INT
	DECLARE @xmlDataVenta XML
	DECLARE curDatos CURSOR 
	FOR SELECT xm_DAT_TRAN 
		FROM dbo.LOG_TRAN_DATA
		WHERE cd_LOG_STAT= ''P''
		ANd cd_TBL_NAME='''+@cd_TBL_NAME+'''
	CREATE TABLE #tblTemp(' + dbo.db_FC_LOG_TRAN_DATA_GetSchema(@cd_TBL_NAME) + ')
	OPEN curDatos 
	FETCH NEXT FROm curDatos INTO @xmlDataVenta
	WHILE @@FETCH_STATUS=0
	BEGIN
		EXEC sp_xml_preparedocument @hdoc OUTPUT, @xmlDataVenta 
		INSERT INTO #tblTemp(' + dbo.db_FC_LOG_TRAN_DATA_GetColumns(@cd_TBL_NAME) + ')
		SELECT ' + dbo.db_FC_LOG_TRAN_DATA_GetColumns(@cd_TBL_NAME) + ' FROM OPENXML(@hdoc,''//reg'',2)
		WITH (' + dbo.db_FC_LOG_TRAN_DATA_GetSchema(@cd_TBL_NAME) +') 
		FETCH NEXT FROM curDatos INTO @xmlDataVenta
	END
	CLOSE curDatos
	DEALLOCATE curdatos
	SELECT * FROM #tblTemp
	DROP TABLE #tblTemp'
	--SELECT @ds_Datos
	EXEC (@ds_Datos)
END
