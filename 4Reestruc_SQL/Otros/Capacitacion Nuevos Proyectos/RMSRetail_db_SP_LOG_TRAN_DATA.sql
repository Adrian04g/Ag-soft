CREATE PROCEDURE dbo.db_SP_LOG_TRAN_DATA_GetChanges
	@cd_TBL_NAME VARCHAR(20)
AS
BEGIN
	IF NOT EXISTS(SELECT * FROM dbo.LOG_TBL_VERS WHERE cd_TBL_NAME = @cd_TBL_NAME)
	BEGIN
		SELECT 'No se encontro configuracion para Seguimiento de Cambios'
	END
	ELSE
	BEGIN
		IF (dbo.db_FC_LOG_TRAN_DATA_GetKey(@cd_TBL_NAME,'llave') IS NULL)
		BEGIN
			SELECT 'Error al cargar informacion de llave primaria'
			RETURN
		END
		DECLARE @am_VersionDB NUMERIC(10)
		DECLARE @am_VersionAct NUMERIC(10)		
		SELECT @am_VersionDB = CHANGE_TRACKING_CURRENT_VERSION()
		SELECT @am_VersionAct= am_NUM_VERS FROM LOG_TBL_VERS WHERE cd_SRV_NOMB=HOST_NAME() AND cd_TBL_NAME=@cd_TBL_NAME
		SELECT @am_VersionAct=ISNULL(@am_VersionAct,0)
		DECLARE @ds_CadenaSQL VARCHAR(8000)
		SET @ds_CadenaSQL = '
				SELECT CHANG.SYS_CHANGE_OPERATION ,''' + @cd_TBL_NAME + ''' , @@SERVERNAME, (SELECT  '+dbo.db_FC_LOG_TRAN_DATA_GetKey(@cd_TBL_NAME,'llave')+'
						FROM dbo.'+@cd_TBL_NAME+' llave
						WHERE '+dbo.db_FC_LOG_TRAN_DATA_GetKeyJOIN(@cd_TBL_NAME,'llave','TABLA')+'
						FOR XML AUTO,TYPE, ELEMENTS) AS llave
					,(SELECT *
						FROM dbo.'+@cd_TBL_NAME+' reg
						WHERE '+dbo.db_FC_LOG_TRAN_DATA_GetKeyJOIN(@cd_TBL_NAME,'reg','TABLA')+'
						FOR XML AUTO,TYPE, ELEMENTS) AS xmlData
				FROM dbo.' + @cd_TBL_NAME + ' TABLA
				INNER JOIN CHANGETABLE(CHANGES '+@cd_TBL_NAME+','+ CONVERT(VARCHAR(10),@am_VersionAct) + ') AS CHANG ON (' + dbo.db_FC_LOG_TRAN_DATA_GetKeyJOIN(@cd_TBL_NAME,'TABLA','CHANG') + ')
				WHERE CHANG.SYS_CHANGE_VERSION<='+CONVERT(VARCHAR(10),@am_VersionDB)+''
		BEGIN TRY
			BEGIN TRANSACTION
			INSERT INTO LOG_TRAN_DATA(cd_TIP_TRAN,cd_TBL_NAME,cd_BD_ORIG,xm_KEY_TRAN,xm_DAT_TRAN)
			EXEC (@ds_CadenaSQL)
			RAISERROR(@ds_CadenaSQL,10,1) WITH NOWAIT
			UPDATE LOG_TBL_VERS SET am_NUM_VERS = @am_VersionDB WHERE cd_SRV_NOMB=HOST_NAME() AND cd_TBL_NAME=@cd_TBL_NAME 
			COMMIT
		END TRY
		BEGIN CATCH
			SELECT 
				ERROR_NUMBER() AS ErrorNumber
				,ERROR_MESSAGE() AS ErrorMessage;
			ROLLBACK
		END CATCH
	END
END
