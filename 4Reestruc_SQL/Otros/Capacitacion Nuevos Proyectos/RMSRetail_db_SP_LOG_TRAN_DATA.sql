CREATE PROCEDURE dbo.db_SP_LOG_TRAN_DATA_InitializeTable
	@cd_TBL_NAME VARCHAR(200)
AS
BEGIN
	IF EXISTS(SELECT * FROM dbo.LOG_TBL_VERS WHERE cd_TBL_NAME = @cd_TBL_NAME)
	BEGIN
		SELECT 'Tabla ya se encuentra habilitada para Seguimiento de cambios'
	END
	ELSE
	BEGIN
		IF EXISTS(SELECT * FROM SYS.change_tracking_tables WHERE object_id=OBJECT_ID(@cd_TBL_NAME,'U'))
		BEGIN
			SELECT 'WARNING : El seguimiento de cambios ya se encuentra habilitado para esta base de datos'
		END
		ELSE
		BEGIN
			DECLARE @ds_CadenaSQL NVARCHAR(4000)
			SET @ds_CadenaSQL = 'ALTER TABLE dbo.' + @cd_TBL_NAME + ' ENABLE CHANGE_TRACKING'
			EXEC (@ds_CadenaSQL)
		END
		INSERT INTO dbo.LOG_TBL_VERS(cd_SRV_NOMB,cd_TBL_NAME,am_NUM_VERS,dt_LOG_FECHA)
			VALUES(@@SERVERNAME,@cd_TBL_NAME,0,GETDATE())
	END
END
