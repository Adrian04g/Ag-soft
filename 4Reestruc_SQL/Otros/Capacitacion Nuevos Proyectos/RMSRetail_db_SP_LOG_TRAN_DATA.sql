CREATE FUNCTION dbo.db_FC_LOG_TRAN_DATA_GetColumns(
	@cd_TBL_NAME VARCHAR(20) )
RETURNS VARCHAR(4000)
AS
BEGIN
	DECLARE @cd_COL_DEFI VARCHAR(8000)
	SELECT @cd_COL_DEFI = COALESCE(@cd_COL_DEFI + ' , ' + COLUMN_NAME,COLUMN_NAME)
