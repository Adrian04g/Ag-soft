CREATE FUNCTION dbo.db_FC_LOG_TRAN_DATA_GetKey(
	@cd_TBL_NAME VARCHAR(20),
	@ds_ALI_NAME VARCHAR(20) )
RETURNS VARCHAR(4000)
AS
BEGIN
	DECLARE @cd_KEY VARCHAR(1000)
	SELECT @cd_KEY = COALESCE(@cd_KEY+', '+'[Table].'+COLUMN_NAME,'[Table].'+COLUMN_NAME)
		FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE
		WHERE CONSTRAINT_NAME LIKE 'PK_' + @cd_TBL_NAME +'%'
		AND TABLE_CATALOG = DB_NAME()
		ORDER BY ORDINAL_POSITION
	SET @cd_KEY = REPLACE(@cd_KEY,'[Table]','['+@ds_ALI_NAME+']')
	RETURN (IsNull(@cd_KEY,''))
END
GO
