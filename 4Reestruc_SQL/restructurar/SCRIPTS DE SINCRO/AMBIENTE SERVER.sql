ALTER PROCEDURE [dbo].[db_SP_SYN_DATOSTRANSACCION_EnviodecambiosSERVER]
	@cd_TBL_NAME VARCHAR(20),
	@SERVERNAME VARCHAR(3000)
AS
BEGIN
	IF NOT EXISTS(SELECT * FROM dbo.SYN_REG_VERSIONESTABLASERVIDOR WHERE cd_TBL_NAME = @cd_TBL_NAME)
	BEGIN
		SELECT 'No se encontro configuracion para Seguimiento de Cambios'
	END
	ELSE
	BEGIN
		IF (dbo.db_FC_SYN_DATOSTRANSACCION_EnviarllaveSERVER(@cd_TBL_NAME,'llave') IS NULL)
		BEGIN
			SELECT 'Error al cargar informacion de llave primaria'
			RETURN
		END
		DECLARE @codcto VARCHAR(100) = ''''' '
		IF EXISTS(SELECT * FROM INFORMATION_SCHEMA.COLUMNS WHERE COLUMN_NAME = 'CODCTO' AND TABLE_NAME=@cd_TBL_NAME)
			SET @codcto='TABLA.codcto '
		DECLARE @am_VersionDB NUMERIC(10)
		DECLARE @am_VersionAct NUMERIC(10)		
		SELECT @am_VersionDB = CHANGE_TRACKING_CURRENT_VERSION()
		SELECT  @am_VersionAct= am_NUM_VERS FROM SYN_REG_VERSIONESTABLASERVIDOR WHERE cd_SRV_NOMB=@@servername AND cd_TBL_NAME=@cd_TBL_NAME
		IF @SERVERNAME = @@SERVERNAME
		BEGIN
			SET @SERVERNAME = @@SERVERNAME
		END
		--SELECT @am_VersionAct=ISNULL(@am_VersionAct,0)
		DECLARE @ds_CadenaSQL VARCHAR(8000)
		DECLARE @ds_CadenaSQLDelete VARCHAR(8000)
		SET @ds_CadenaSQL = '
			SELECT CHANG.SYS_CHANGE_OPERATION ,''' + @cd_TBL_NAME + ''' , (SELECT '+dbo.db_FC_SYN_DATOSTRANSACCION_EnviarllaveSERVER(@cd_TBL_NAME,'llave')+'
				FROM dbo.'+@cd_TBL_NAME+' llave
				WHERE '+dbo.db_FC_SYN_DATOSTRANSACCION_EnviarllaveSERVERJOINSERVER(@cd_TBL_NAME,'llave','TABLA')+'
				FOR XML PATH(''reg'')) AS llave
				,(SELECT *,'''+@SERVERNAME+''' AS cd_BD_ORIG, CHANG.SYS_CHANGE_VERSION AS am_LOG_TRAN
				FROM dbo.'+@cd_TBL_NAME+' reg
				WHERE '+dbo.db_FC_SYN_DATOSTRANSACCION_EnviarllaveSERVERJOINSERVER(@cd_TBL_NAME,'reg','TABLA')+'
				FOR XML PATH(''reg'')) AS xmlData,
				CHANG.SYS_CHANGE_VERSION,
				IsNull(SERVIDOR,''SERVER'') AS cd_BD_ORIG,
				'+@codcto+' AS codcto
			FROM dbo.' + @cd_TBL_NAME + ' TABLA
			INNER JOIN CHANGETABLE(CHANGES '+@cd_TBL_NAME+','+ CONVERT(VARCHAR(10),@am_VersionAct) + ') AS CHANG ON (' + dbo.db_FC_SYN_DATOSTRANSACCION_EnviarllaveSERVERJOINSERVER(@cd_TBL_NAME,'TABLA','CHANG') + ')
			WHERE CHANG.SYS_CHANGE_VERSION BETWEEN ' + CONVERT(VARCHAR(10),@am_VersionAct) + ' AND '+ CONVERT(VARCHAR(10),@am_VersionDB) + 'ORDER BY CHANG.SYS_CHANGE_VERSION ASC'
		SET @ds_CadenaSQLDelete = '
			WITH tblCambios AS (
				SELECT SYS_CHANGE_VERSION, SYS_CHANGE_CREATION_VERSION, SYS_CHANGE_OPERATION, SYS_CHANGE_COLUMNS, SYS_CHANGE_CONTEXT
					, '+dbo.db_FC_SYN_DATOSTRANSACCION_EnviarllaveSERVER(@cd_TBL_NAME,'chg')+'
					FROM CHANGETABLE(CHANGES '+@cd_TBL_NAME+','+ CONVERT(VARCHAR(10),@am_VersionAct) + ') chg
				WHERE chg.SYS_CHANGE_VERSION BETWEEN ' + CONVERT(VARCHAR(10),@am_VersionAct) + ' AND '+ CONVERT(VARCHAR(10),@am_VersionDB) + ' 
				AND chg.SYS_CHANGE_OPERATION =''D'')
			SELECT CHANG.SYS_CHANGE_OPERATION ,''' + @cd_TBL_NAME + ''' 
				, (SELECT '+dbo.db_FC_SYN_DATOSTRANSACCION_EnviarllaveSERVER(@cd_TBL_NAME,'chg')+'
					FROM tblCambios chg
					WHERE chg.SYS_CHANGE_VERSION=CHANG.SYS_CHANGE_VERSION
					AND '+dbo.db_FC_SYN_DATOSTRANSACCION_EnviarllaveSERVERJOINSERVER(@cd_TBL_NAME,'chg','CHANG')+'
					FOR XML PATH(''chg'')) AS llave
				, NULL AS xmlData
				, CHANG.SYS_CHANGE_VERSION
				, ''SERVER'' AS cd_BD_ORIG
				, '''' AS codcto
			FROM tblCambios CHANG
			ORDER BY CHANG.SYS_CHANGE_VERSION ASC'

			BEGIN TRY
				BEGIN TRANSACTION
				--PRINT @ds_CadenaSQL
				INSERT INTO SYN_DATOSTRANSACCION(cd_TIP_TRAN,cd_TBL_NAME,xm_KEY_TRAN,xm_DAT_TRAN,VersionA,cd_BD_ORIG,codcto)
				EXEC (@ds_CadenaSQL)
				INSERT INTO SYN_DATOSTRANSACCION(cd_TIP_TRAN,cd_TBL_NAME,xm_KEY_TRAN,xm_DAT_TRAN,VersionA,cd_BD_ORIG,codcto)
				EXEC (@ds_CadenaSQLDelete)
				
				UPDATE SYN_REG_VERSIONESTABLASERVIDOR SET am_NUM_VERS = @am_VersionDB WHERE	
					cd_TBL_NAME=@cd_TBL_NAME
				
			COMMIT
			--UPDATE SYN_DATOSTRANSACCION SET cd_BD_ORIG = 'SERVER' WHERE cd_BD_ORIG IS NULL
		END TRY
		BEGIN CATCH
			SELECT
				@cd_TBL_NAME AS Tabla 
				,ERROR_NUMBER() AS ErrorNumber
				,ERROR_MESSAGE() AS ErrorMessage;
			ROLLBACK
		END CATCH
	END
END